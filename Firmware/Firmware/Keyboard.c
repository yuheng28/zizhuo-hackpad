{
	bool ConfigSuccess = true;

	ConfigSuccess &= HID_Device_ConfigureEndpoints(&Keyboard_HID_Interface);

	USB_Device_EnableSOFEvents();

	//LEDs_SetAllLEDs(ConfigSuccess ? LEDMASK_USB_READY : LEDMASK_USB_ERROR);
}

/** Event handler for the library USB Control Request reception event. */
void EVENT_USB_Device_ControlRequest(void)
{
	HID_Device_ProcessControlRequest(&Keyboard_HID_Interface);
}

/** Event handler for the USB device Start Of Frame event. */
void EVENT_USB_Device_StartOfFrame(void)
{
	HID_Device_MillisecondElapsed(&Keyboard_HID_Interface);
	
	// update paw_timer
	if (paw_timer_in_ms > 0) paw_timer_in_ms--;
	
	if (paw_timer_in_ms == 0 && paw_state == PAW_DOWN) paw_state = PAW_UP;
}

/** HID class driver callback function for the creation of HID reports to the host.
 *
 *  \param[in]     HIDInterfaceInfo  Pointer to the HID class interface configuration structure being referenced
 *  \param[in,out] ReportID    Report ID requested by the host if non-zero, otherwise callback should set to the generated report ID
 *  \param[in]     ReportType  Type of the report to create, either HID_REPORT_ITEM_In or HID_REPORT_ITEM_Feature
 *  \param[out]    ReportData  Pointer to a buffer where the created report should be stored
 *  \param[out]    ReportSize  Number of bytes written in the report (or zero if no report is to be sent)
 *
 *  \return Boolean \c true to force the sending of the report, \c false to let the library determine if it needs to be sent
 */
bool CALLBACK_HID_Device_CreateHIDReport(USB_ClassInfo_HID_Device_t* const HIDInterfaceInfo,
                                         uint8_t* const ReportID,
                                         const uint8_t ReportType,
                                         void* ReportData,
                                         uint16_t* const ReportSize)
{
	USB_KeyboardReport_Data_t* KeyboardReport = (USB_KeyboardReport_Data_t*)ReportData;

	memset(KeyboardReport, 0, sizeof(USB_KeyboardReport_Data_t));

	uint8_t UsedKeyCodes = 0;
	bool key_pressed = false;
	
	if(!(PINB&(1<<PB1))) {
		key_pressed = true;
		KeyboardReport->KeyCode[UsedKeyCodes++] = HID_KEYBOARD_SC_1_AND_EXCLAMATION;
	}
	
	if(!(PINB&(1<<PB2))) {
		key_pressed = true;
		KeyboardReport->KeyCode[UsedKeyCodes++] = HID_KEYBOARD_SC_2_AND_AT;
	}
	
	if(!(PINB&(1<<PB3))) {
		key_pressed = true;
		KeyboardReport->KeyCode[UsedKeyCodes++] = HID_KEYBOARD_SC_3_AND_HASHMARK;
	}
	
	if(!(PINB&(1<<PB4))) {
		key_pressed = true;
		KeyboardReport->KeyCode[UsedKeyCodes++] = HID_KEYBOARD_SC_4_AND_DOLLAR;
	}
	
	if(!(PINB&(1<<PB5))) {
		key_pressed = true;
		KeyboardReport->KeyCode[UsedKeyCodes++] = HID_KEYBOARD_SC_5_AND_PERCENTAGE;
	}
	
	if(!(PINB&(1<<PB6))) {
		key_pressed = true;
		KeyboardReport->KeyCode[UsedKeyCodes++] = HID_KEYBOARD_SC_6_AND_CARET;
	}
	
	if (key_pressed) {
		paw_state = PAW_DOWN;
		paw_timer_in_ms = PAW_DOWN_TIME_MS;
	}

	*ReportSize = sizeof(USB_KeyboardReport_Data_t);
	return false;
}

